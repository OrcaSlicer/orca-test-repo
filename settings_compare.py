def type_of(key: str) -> str | None:
    import surface

    return surface.type_map().get(key)


def is_variant_key(key: str) -> bool:
    """VARIANT_KEYS above is the fallback list (copied from one checkout); the
    live/snapshotted surface's own `variant_keys` extends it, so a newer build's
    additions are picked up without editing this file."""
    import surface

    return key in VARIANT_KEYS or key in surface.variant_keys()


# ---------------------------------------------------------------- G-code side

_LINE_RE = re.compile(r"^; ([A-Za-z0-9_]+) = (.*)$")


def extract_config_block(gcode_text: str) -> str:
    if BLOCK_START not in gcode_text:
        raise ValueError(f"{BLOCK_START!r} not found in G-code")
    after = gcode_text.split(BLOCK_START, 1)[1]
    if BLOCK_END not in after:
        raise ValueError(f"{BLOCK_END!r} not found in G-code")
    return after.split(BLOCK_END, 1)[0]


def parse_gcode_config_raw(gcode_text: str) -> dict[str, str]:
    """`; key = value` lines of the config block, values still encoded."""
    out = {}
    for line in extract_config_block(gcode_text).splitlines():
        m = _LINE_RE.match(line)
        if m:
            out[m.group(1)] = m.group(2)
    return out


def unescape_cstyle(s: str) -> str:
    out = []
    i = 0
    while i < len(s):
        c = s[i]
        if c == "\\" and i + 1 < len(s):
            n = s[i + 1]
            out.append({"n": "\n", "r": "\r"}.get(n, n))
            i += 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


def split_string_vector(s: str) -> list[str]:
    """Inverse of escape_strings_cstyle: ';'-separated, optionally quoted."""
    items, i, n = [], 0, len(s)
    if s == "":
        return []
    while i <= n:
        if i < n and s[i] == '"':
            i += 1
            buf = []
            while i < n and s[i] != '"':
                if s[i] == "\\" and i + 1 < n:
                    buf.append({"n": "\n", "r": "\r"}.get(s[i + 1], s[i + 1]))
                    i += 2
                else:
                    buf.append(s[i])
                    i += 1
            items.append("".join(buf))
            i += 1  # closing quote
        else:
            j = s.find(";", i)
            if j == -1:
                j = n
            items.append(s[i:j])
            i = j
        if i < n and s[i] == ";":
            i += 1
            if i == n:
                items.append("")
                break
        else:
            break
    return items


_UNTYPED_CSV_RE = re.compile(r"[-+0-9.%a-z_]*(,[-+0-9.%a-z_]*)+")


def decode_gcode_value(key: str, raw: str):
    t = type_of(key)
    if t in STRING_VECTOR_TYPES:
        return split_string_vector(raw)
    if t in COMMA_VECTOR_TYPES:
        return [] if raw == "" else raw.split(",")
    if t == "coString":
        return unescape_cstyle(raw)
    if t is None and _UNTYPED_CSV_RE.fullmatch(raw):
        # A few options (e.g. the nullable per-filament `filament_*_when_cut`
        # overrides) are registered outside the pattern enumerate_cli_options.py
        # scans, so they have no type here; a bare comma list of simple tokens
        # (numbers, percentages, enum names, `nil`) is unambiguously a vector.
        return raw.split(",")
    return raw


def parse_gcode_config(gcode_text: str) -> dict:
    return {k: decode_gcode_value(k, v) for k, v in parse_gcode_config_raw(gcode_text).items()}


# ------------------------------------------------------------------ JSON side

def decode_json_value(key: str, v):
    if isinstance(v, list):
        return [str(x) for x in v]
    return str(v)


def parse_settings_json(text: str) -> dict:
    return {k: decode_json_value(k, v) for k, v in json.loads(text).items()}


def read_3mf_member(path: Path, member: str) -> str:
    with zipfile.ZipFile(path) as zf:
        return zf.read(member).decode("utf-8", errors="replace")


def read_3mf_project_settings(path: Path) -> dict:
    return parse_settings_json(read_3mf_member(path, "Metadata/project_settings.config"))


def read_3mf_gcode_config(path: Path, plate: int = 1) -> dict:
    return parse_gcode_config(read_3mf_member(path, f"Metadata/plate_{plate}.gcode"))


# ------------------------------------------------------------------ compare

def _num_eq(a: str, b: str) -> bool:
    if a == b:
        return True
    try:
        return float(a.rstrip("%")) == float(b.rstrip("%")) and a.endswith("%") == b.endswith("%")
    except ValueError:
        return False


def _is_subsequence(small: list, big: list) -> bool:
    it = iter(big)
    return all(any(_num_eq(s, x) for x in it) for s in small)


