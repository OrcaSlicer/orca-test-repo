def values_match(key: str, gcode_val, json_val) -> bool:
    """True if a G-code block value and a merged-JSON value agree, allowing the
    documented encoding differences (numeric formatting, variant expansion,
    and the slicer padding a short per-filament vector out to filament count)."""
    if isinstance(gcode_val, str) and isinstance(json_val, list) and type_of(key) is None:
        # untyped key (not in the surface snapshot) that is evidently a vector
        gcode_val = gcode_val.split(",") if gcode_val != "" else []
    if isinstance(gcode_val, list) != isinstance(json_val, list):
        gcode_l = gcode_val if isinstance(gcode_val, list) else [gcode_val]
        json_l = json_val if isinstance(json_val, list) else [json_val]
    else:
        gcode_l, json_l = gcode_val, json_val
    if isinstance(gcode_l, list):
        if len(gcode_l) == len(json_l):
            return all(_num_eq(a, b) for a, b in zip(gcode_l, json_l))
        if len(json_l) < len(gcode_l):
            # JSON under-specified (fewer elements than filaments); the slicer pads.
            return all(_num_eq(a, b) for a, b in zip(gcode_l, json_l))
        if is_variant_key(key):
            return _is_subsequence(gcode_l, json_l)
        return False
    return _num_eq(gcode_l, json_l)


def compare_gcode_to_json(gcode_cfg: dict, json_cfg: dict, ignore: set[str] = frozenset()):
    """Return [(key, gcode_value, json_value)] for every common key that disagrees."""
    mismatches = []
    for k in sorted(set(gcode_cfg) & set(json_cfg) - set(ignore)):
        if not values_match(k, gcode_cfg[k], json_cfg[k]):
            mismatches.append((k, gcode_cfg[k], json_cfg[k]))
    return mismatches


def expect_from_preset_file(path: Path) -> dict:
    """The (key -> value) pairs a preset JSON asks for, i.e. everything except
    its own metadata. Used to derive probe expectations from a fixture file
    instead of hard-coding them in a test."""
    META = {"type", "from", "name", "inherits", "instantiation", "version", "setting_id",
            "filament_id", "compatible_printers", "compatible_prints", "compatible_printers_condition",
            "compatible_prints_condition", "is_custom_defined", "renamed_from", "upward_compatible_machine",
            "printer_model", "printer_variant", "default_print_profile", "default_filament_profile",
            "filament_settings_id", "print_settings_id", "printer_settings_id", "model_id",
            "filament_vendor", "description", "alias"}
    d = json.loads(path.read_text())
    return {k: decode_json_value(k, v) for k, v in d.items() if k not in META}
