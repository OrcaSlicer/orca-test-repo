"""Parse and compare the settings OrcaSlicer records in its outputs.

Three artifacts carry "the settings used", in two different encodings:

* The G-code's `; CONFIG_BLOCK_START` .. `; CONFIG_BLOCK_END` section -- one
  `; key = value` line per option, serialized by libslic3r's own option
  serializers (GCode.cpp `append_full_config`, from `print.full_print_config()`
  minus a small `banned_keys` set). This is the config the slicer *applied*.
* `Metadata/project_settings.config` inside an exported 3mf, and the file
  written by `--export-settings` -- the same `DynamicPrintConfig` saved as
  JSON (scalars as strings, vectors as lists of strings). This is the
  *merged* config before per-plate apply, so keys in the *variant* sets
  below may carry N_filaments x N_variants elements where the G-code carries
  one element per filament.

Value encodings, from libslic3r/Config.cpp:
  scalar string  -> raw text, C-style escaped (\\n \\r \\\\ \\")     [escape_string_cstyle]
  string vector  -> ';'-separated, elements quoted+escaped if they contain
                    space/tab/;/\\/"/CR/LF (or a single empty string)   [escape_strings_cstyle]
  numeric/bool/percent/point vectors -> ','-separated
The option type per key comes from cases/_snapshots/cli_surface_full.json
(generated by scripts/enumerate_cli_options.py); keys not listed there
(e.g. the `first_layer_*`/`bed_shape` extras GCode.cpp appends) are compared
as plain strings.
"""
